    def fetch_profile(self, profile_id_or_url: str) -> Optional[ProfileResponse]:
        for p in self._profiles:
            if p.id == profile_id_or_url or p.profile_url == profile_id_or_url:
                return p
        return None

    def get_all_profiles(self) -> List[ProfileResponse]:
        return self._profiles
